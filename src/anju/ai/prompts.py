from __future__ import annotations

from typing import Any


def build_highlight_prompt(
    *,
    metadata: dict[str, Any],
    subtitles: str,
    max_highlights: int,
) -> str:
    """見どころ抽出用プロンプトを作成する。"""
    title = metadata.get("title") or "不明"
    uploader = metadata.get("uploader") or "不明"

    return f"""
あなたはゲーム配信の切り抜き動画を企画する編集者です。

以下はTwitch配信のSRT字幕です。
YouTubeの横動画またはショート動画に向く見どころを、
最大{max_highlights}件選んでください。

配信者: {uploader}
配信タイトル: {title}

選定方針:
歌唱シーンを積極的に見どころとして採用してください。
特に、ゲーム配信中に歌っている場面を高く評価してください。

優先順位:
1. ゲームをプレイしながら歌っている場面
2. 歌唱に熱中している場面、長く歌っている場面
3. 歌唱中の面白い反応や、歌とゲームの状況が重なる場面
4. 驚き、悲鳴、笑い、失敗、予想外の出来事
5. その他、視聴者が楽しめる特徴的な場面

歌唱シーンの選定ルール:
- 歌詞と思われる文章が連続している場合は、歌唱シーンの可能性を考慮する
- 歌の途中だけでなく、可能な限り歌い始めから歌い終わりまでを含める
- 歌唱が長く続く場合は、内容が成立する範囲で区切る
- ゲームプレイと歌唱が同時に起きている場合は特に優先する
- 歌唱シーンは、通常のリアクション系の見どころと同様に評価する
- 単なる会話や雑談を、根拠なく歌唱と判断しない

全体の選定ルール:
- 歌唱シーンだけで候補を埋めず、通常の面白い場面も残す
- 驚き、悲鳴、笑い、失敗、予想外の出来事も評価する
- 視聴者が状況を理解しやすい場面を選ぶ
- 前後を含めて30秒から120秒程度で成立する場面を選ぶ
- 同じ場面を重複して選ばない
- 内容が薄い場面は無理に選ばない
- 開始時刻と終了時刻はSRTを根拠にする
- 必要なら前後の文脈を少し広めに含める
- 歌唱と判断した理由を、見どころの説明に簡潔に含める
- 日本語で回答する

注意:
SRT字幕だけでは実際に歌っているか断定できない場合があります。
歌詞の連続性や発言内容から判断し、確信が持てない場合は
歌唱と断定せず、通常の見どころとして評価してください。

SRT字幕:
{subtitles}
""".strip()


def build_thumbnail_prompt(
    *,
    metadata: dict[str, Any],
    highlights: list[dict[str, Any]],
) -> str:
    """サムネイル案生成用プロンプトを作成する。"""
    title = metadata.get("title") or "不明"
    uploader = metadata.get("uploader") or "不明"

    return f"""
あなたはYouTubeのゲーム動画に詳しいサムネイルデザイナーです。

各見どころについて、内容を誇張しすぎず、
一目で状況と感情が伝わるサムネイル案を作成してください。

配信者: {uploader}
配信タイトル: {title}

要件:
- main_textは短く、読みやすい日本語にする
- sub_textは必要最低限にする
- 文字を多くしすぎない
- 強い感情や状況が伝わる構図にする
- 背景、人物、敵、文字の配置を具体的に示す
- 推奨色を具体的に示す
- 既存キャラクターの見た目を過度に変更しない
- 各案がどのクリップに対応するか明記する

見どころ一覧:
{highlights}
""".strip()
